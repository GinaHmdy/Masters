"""
Regenerate README section 3 (the PPD v6 cross-dataset result tables) from results/phase1_*.json.

Same rationale as make_canonical.py: these tables drifted badly. Section 3 held PPD v6's KuaiRec
AvgPop@20 as 967.43 -- the pre-fix all-user value -- long after the test-user scope fix put it at
1616.19, and its Yahoo row quoted a test-set-selected configuration. Hand-maintained result
tables in a README do not survive a protocol change; generated ones do.

The region rewritten is delimited by markers so the surrounding prose is preserved.
"""
import json
import os

CODE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(CODE))
RESULTS = os.path.join(CODE, "results")
TARGET = os.path.join(ROOT, "README.md")
BEGIN = "<!-- BEGIN GENERATED V6 TABLES -->"
END = "<!-- END GENERATED V6 TABLES -->"

ORDER = ["LightGCN", "TSP", "PPD v3", "PPD v4", "PPD v6"]
COLS = [("recall@20", "Recall@20", 6), ("ndcg@20", "NDCG@20", 6),
        ("precision@20", "Precision@20", 6), ("avgpop@20", "AvgPop@20", 2),
        ("coverage@20", "Coverage@20", 4), ("aplt@20", "APLT@20", 4),
        ("gini@20", "Gini@20", 4)]

# Higher is better for everything except AvgPop and Gini.
LOWER_BETTER = {"avgpop@20", "gini@20"}

NOTE = {
    "Gowalla": "**Sparse.** Test users are 100% of all users, so no protocol fix moves these "
               "numbers -- which is why this is the result the thesis leads with.",
    "Yahoo": "**Dense.** Only 16.6% of users appear in the test split; every row describes that "
             "minority. AvgPop is scoped to test users (audit finding L).",
    "KuaiRec": "**Dense.** Candidates restricted to the 3,247-item test universe (finding P) AND "
               "AvgPop scoped to test users (finding L). Both fixes bite hard here.",
    "Coat": "**Small/dense.** Test users are 96.9% of all users. TSP builds zero edges on Coat and "
            "never runs, so its rows are identical to LightGCN by construction (finding S).",
}


def load(ds):
    data = {}
    for suffix in ("", "_v6"):
        p = os.path.join(RESULTS, f"phase1_{ds.lower()}{suffix}.json")
        if os.path.exists(p):
            with open(p) as f:
                data.update(json.load(f))
    return data


def _protocol_line():
    """Report the seeds actually present, rather than asserting a count that can go stale."""
    seeds = set()
    for ds in ("Gowalla", "Yahoo", "KuaiRec", "Coat"):
        for m in load(ds).values():
            seeds |= set(m.get("seeds", {}))
    listed = ", ".join(sorted(seeds))
    return (f"*Protocol: {len(seeds)} seeds ({listed}), mean ± population std. "
            "Best value per column in bold.*")


def main():
    out = [BEGIN, "",
           "*Generated by `make_readme_tables.py` from `results/phase1_*.json` -- do not hand-edit.*",
           _protocol_line(),
           "*Significance tests vs LightGCN live in `results/significance_*.json`; the narrative "
           "reading is in `THESIS_AUDIT.md` findings T-V.*", ""]
    for ds in ("Gowalla", "Yahoo", "KuaiRec", "Coat"):
        data = load(ds)
        if not data:
            continue
        rows = [m for m in ORDER if m in data]
        out += [f"### {ds}", "", NOTE.get(ds, ""), ""]
        out.append("| Method | " + " | ".join(c[1] for c in COLS) + " |")
        out.append("|---|" + "---|" * len(COLS))
        best = {}
        for key, _, _ in COLS:
            vals = [data[m]["mean"][key] for m in rows if key in data[m]["mean"]]
            if vals:
                best[key] = min(vals) if key in LOWER_BETTER else max(vals)
        for m in rows:
            mean, std = data[m]["mean"], data[m]["std"]
            cells = []
            for key, _, prec in COLS:
                if key not in mean:
                    cells.append("--")
                    continue
                txt = f"{mean[key]:.{prec}f} ± {std.get(key, 0.0):.{prec}f}"
                if key in best and abs(mean[key] - best[key]) < 1e-12:
                    txt = f"**{txt}**"
                cells.append(txt)
            label = f"**{m} (Ours)**" if m == "PPD v6" else m
            out.append(f"| {label} | " + " | ".join(cells) + " |")
        out += ["", "---", ""]
    out += [END]

    with open(TARGET, encoding="utf-8") as f:
        text = f.read()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"markers {BEGIN} / {END} not found in {TARGET}")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(head + "\n".join(out) + tail)
    print(f"[updated] {TARGET}")


if __name__ == "__main__":
    main()
