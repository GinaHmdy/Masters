"""
Regenerate the per-dataset result tables in RESULTS_CANONICAL.md from results/phase1_*.json.

RESULTS_CANONICAL.md is the single source the manuscript quotes, and it has historically drifted
from the JSON it claims to summarise (the README held four different values for Gowalla LightGCN
Recall@20 simultaneously). Generating the tables mechanically removes that failure mode: if a
number is in the file, a run produced it.

Only the region between the DATASET TABLES markers is rewritten; prose outside is preserved.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RESULTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
TARGET = os.path.join(ROOT, "RESULTS_CANONICAL.md")
BEGIN = "<!-- BEGIN GENERATED DATASET TABLES -->"
END = "<!-- END GENERATED DATASET TABLES -->"

ORDER = ["LightGCN", "TSP", "PPD v3", "PPD v4", "PPD v6"]
COLS = [("recall@20", "Recall@20", 6), ("ndcg@20", "NDCG@20", 6),
        ("precision@20", "Precision@20", 6), ("avgpop@20", "AvgPop@20", 2),
        ("coverage@20", "Coverage@20", 4), ("aplt@20", "APLT@20", 4),
        ("gini@20", "Gini@20", 4)]
DESC = {
    "Gowalla": "sparse - test users are 100% of all users, so neither protocol fix moves it",
    "Yahoo": "dense - test users are 16.6% of all users; AvgPop regenerated under the scope fix",
    "KuaiRec": "dense - candidate-restricted AND test-user scoped; both fixes bite here",
    "Coat": "small/dense - test users are 96.9% of all users",
}


def load(ds):
    data = {}
    for suffix in ("", "_v6"):
        p = os.path.join(RESULTS, f"phase1_{ds.lower()}{suffix}.json")
        if os.path.exists(p):
            with open(p) as f:
                data.update(json.load(f))
    return data


def cell(mean, std, key, prec):
    if key not in mean:
        return "--"
    return f"{mean[key]:.{prec}f} ± {std.get(key, 0.0):.{prec}f}"


def main():
    out = [BEGIN, "",
           "*Generated by `LightGCN/code/make_canonical.py` from `results/phase1_*.json`.*",
           "*Mean ± population std over seeds. Do not hand-edit; re-run the generator.*", ""]
    for ds in ("Gowalla", "Yahoo", "KuaiRec", "Coat"):
        data = load(ds)
        if not data:
            continue
        seeds = sorted({s for m in data.values() for s in m.get("seeds", {})})
        counts = {m: len(data[m].get("seeds", {})) for m in ORDER if m in data}
        out += [f"### {ds}", "", f"*{DESC[ds]}. Seeds: {', '.join(seeds)}.*", "",
                "| Method | n | " + " | ".join(c[1] for c in COLS) + " |",
                "|" + "---|" * (len(COLS) + 2)]
        for m in ORDER:
            if m not in data:
                continue
            mean, std = data[m]["mean"], data[m]["std"]
            out.append(f"| {m} | {counts[m]} | "
                       + " | ".join(cell(mean, std, k, p) for k, _, p in COLS) + " |")
        missing = [m for m in ORDER if m not in data]
        out.append("")
        # An unequal n across rows is a comparison across different amounts of evidence.
        # It must be visible in the table, not inferred from a seed list in the caption.
        if len(set(counts.values())) > 1:
            lo, hi = min(counts.values()), max(counts.values())
            uneven = ", ".join(f"{m} (n={c})" for m, c in sorted(counts.items(), key=lambda kv: kv[1]))
            out += [f"> **Unequal seed counts on {ds}** ({lo} vs {hi}): {uneven}. Means and stds "
                    f"below are over different numbers of runs, so the ± columns are not directly "
                    f"comparable between rows. Paired significance tests intersect on the shared "
                    f"seeds only and are unaffected.", ""]
        if missing:
            out += [f"> Not yet regenerated under the frozen protocol: **{', '.join(missing)}**.", ""]
    out.append(END)
    block = "\n".join(out)

    with open(TARGET) as f:
        doc = f.read()
    if BEGIN in doc and END in doc:
        doc = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    else:
        doc = doc.rstrip("\n") + "\n\n" + block + "\n"
    with open(TARGET, "w") as f:
        f.write(doc)
    print(block)
    print(f"\n[updated] {TARGET}")


if __name__ == "__main__":
    main()
